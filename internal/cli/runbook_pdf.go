package cli

import (
	"bytes"
	"fmt"
	"strings"

	"github.com/go-pdf/fpdf"

	"github.com/hriday/meridian/internal/version"
)

// RenderRunbookPDF lays an already-run runbook out as a presentation-quality PDF:
// a branded header band, a pass/fail summary, and one card per step with its
// command, a status pill, and its output in a monospaced code block. Generated
// entirely in Go so it works in the desktop webview, where browser print-to-PDF
// is a no-op (macOS WKWebView doesn't implement window.print).
func RenderRunbookPDF(d RunbookData) ([]byte, error) {
	const (
		marginX  = 15.0
		contentW = 180.0
	)
	pdf := fpdf.New("P", "mm", "A4", "")
	pdf.SetMargins(marginX, 15, marginX)
	pdf.SetAutoPageBreak(true, 18)
	tr := pdf.UnicodeTranslatorFromDescriptor("")
	pageW, pageH := pdf.GetPageSize()

	ver := strings.TrimSpace(version.Version)
	brand := "Generated by Meridian"
	if ver != "" {
		brand += " " + ver
	}
	pdf.SetFooterFunc(func() {
		pdf.SetY(-12)
		pdf.SetFont("Helvetica", "", 7)
		pdf.SetTextColor(150, 150, 155)
		pdf.CellFormat(0, 5, tr(brand), "", 0, "L", false, 0, "")
		pdf.CellFormat(0, 5, fmt.Sprintf("Page %d", pdf.PageNo()), "", 0, "R", false, 0, "")
	})

	pdf.AddPage()

	name := d.Name
	if name == "" {
		name = d.Profile
	}

	// Header band — full-bleed dark band with the brand, title and target.
	pdf.SetFillColor(15, 42, 46)
	pdf.Rect(0, 0, pageW, 36, "F")
	pdf.SetXY(marginX, 8.5)
	pdf.SetFont("Helvetica", "B", 8)
	pdf.SetTextColor(90, 200, 180)
	pdf.CellFormat(0, 5, tr("MERIDIAN  ·  NETWORK RUNBOOK"), "", 1, "L", false, 0, "")
	pdf.SetX(marginX)
	pdf.SetFont("Helvetica", "B", 19)
	pdf.SetTextColor(255, 255, 255)
	pdf.CellFormat(0, 10, tr(name), "", 1, "L", false, 0, "")
	pdf.SetX(marginX)
	pdf.SetFont("Helvetica", "", 9)
	pdf.SetTextColor(200, 218, 214)
	meta := "Target: " + d.Target
	if d.Generated != "" {
		meta += "        " + d.Generated
	}
	pdf.CellFormat(0, 5, tr(meta), "", 1, "L", false, 0, "")

	// Summary chips.
	ok, failed := 0, 0
	for _, s := range d.Steps {
		if s.OK {
			ok++
		} else {
			failed++
		}
	}
	pdf.SetY(44)
	pdf.SetX(marginX)
	pdf.SetFont("Helvetica", "", 10)
	pdf.SetTextColor(110, 114, 120)
	pdf.CellFormat(0, 6, fmt.Sprintf("%d steps", len(d.Steps)), "", 1, "L", false, 0, "")
	chipY := pdf.GetY()
	drawChip(pdf, marginX, chipY, fmt.Sprintf("%d passed", ok), 38, 148, 86)
	if failed > 0 {
		w := pdf.GetStringWidth(fmt.Sprintf("%d passed", ok)) + 8
		drawChip(pdf, marginX+w+4, chipY, fmt.Sprintf("%d failed", failed), 201, 62, 62)
	}
	pdf.SetY(chipY + 11)
	pdf.SetTextColor(0, 0, 0)

	for _, s := range d.Steps {
		drawStep(pdf, tr, s, marginX, contentW, pageH)
	}

	var buf bytes.Buffer
	if err := pdf.Output(&buf); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// drawChip draws a small rounded, filled pill with white centred text.
func drawChip(pdf *fpdf.Fpdf, x, y float64, label string, r, g, b int) {
	pdf.SetFont("Helvetica", "B", 8)
	w := pdf.GetStringWidth(label) + 8
	pdf.SetFillColor(r, g, b)
	pdf.RoundedRect(x, y, w, 6, 1.2, "1234", "F")
	pdf.SetXY(x, y)
	pdf.SetTextColor(255, 255, 255)
	pdf.CellFormat(w, 6, label, "", 0, "C", false, 0, "")
}

// drawStep renders one step as a card: a shaded header bar with the command and
// a status pill, then the output in a bordered monospace code block.
func drawStep(pdf *fpdf.Fpdf, tr func(string) string, s RunbookStep, marginX, contentW, pageH float64) {
	cmd := s.Command
	if len(s.Args) > 0 {
		cmd += " " + strings.Join(s.Args, " ")
	}
	// Keep the header bar off the very bottom of a page.
	if pdf.GetY() > pageH-40 {
		pdf.AddPage()
	}

	y := pdf.GetY()
	pdf.SetFillColor(243, 245, 247)
	pdf.RoundedRect(marginX, y, contentW, 9, 1.2, "1234", "F")

	pill, pr, pg, pb := "OK", 38, 148, 86
	if !s.OK {
		pill, pr, pg, pb = "FAILED", 201, 62, 62
	}
	const pw = 18.0
	pdf.SetFillColor(pr, pg, pb)
	pdf.RoundedRect(marginX+contentW-pw-2, y+2, pw, 5, 1.0, "1234", "F")
	pdf.SetXY(marginX+contentW-pw-2, y+2)
	pdf.SetFont("Helvetica", "B", 7)
	pdf.SetTextColor(255, 255, 255)
	pdf.CellFormat(pw, 5, pill, "", 0, "C", false, 0, "")

	pdf.SetXY(marginX+3, y+2)
	pdf.SetFont("Helvetica", "B", 10)
	pdf.SetTextColor(33, 37, 41)
	pdf.CellFormat(contentW-pw-8, 5, tr(cmd), "", 0, "L", false, 0, "")

	pdf.SetY(y + 10.5)
	out := wrapLong(sanitizePDF(s.Output), 98)
	if strings.TrimSpace(out) == "" {
		out = "(no output)"
	}
	pdf.SetX(marginX)
	pdf.SetFont("Courier", "", 8)
	pdf.SetTextColor(60, 62, 68)
	pdf.SetFillColor(249, 249, 251)
	pdf.SetDrawColor(224, 226, 230)
	pdf.SetLineWidth(0.2)
	pdf.MultiCell(contentW, 4.2, tr(out), "L", "L", true)
	pdf.Ln(5)
}

// sanitizePDF replaces common non-latin-1 glyphs (box drawing, check marks,
// arrows) with ASCII so the core PDF fonts render them legibly.
func sanitizePDF(s string) string {
	return strings.NewReplacer(
		"✓", "[ok]", "✔", "[ok]", "✗", "[x]", "✘", "[x]", "×", "x",
		"•", "-", "·", "-", "→", "->", "←", "<-", "…", "...",
		"─", "-", "│", "|", "├", "|", "└", "|", "┌", "|", "┐", "|", "┘", "|",
		"⚠", "(!)", "°", " deg", "’", "'", "“", "\"", "”", "\"",
	).Replace(s)
}

// wrapLong hard-wraps any line longer than max runes, so a long unbroken token
// (a hash, a base64 blob) can't overflow the PDF cell width.
func wrapLong(s string, max int) string {
	var out []string
	for _, line := range strings.Split(s, "\n") {
		r := []rune(line)
		for len(r) > max {
			out = append(out, string(r[:max]))
			r = r[max:]
		}
		out = append(out, string(r))
	}
	return strings.Join(out, "\n")
}
