// runDocs generates a full tool reference — every command grouped by area with
// its usage and description, plus the runbook recipes — as Markdown, HTML or
// PDF. It's generated straight from the catalog (Catalog() and the runbook
// profiles), so it can't drift from what the app actually ships.
func runDocs(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet("docs", flag.ContinueOnError)
	fs.SetOutput(stderr)
	format := fs.String("format", "md", "output format: md, html, or pdf")
	out := fs.String("out", "", "write to this file instead of stdout")
	if _, ok := parsePositionals(fs, args); !ok {
		return 2
	}

	var data []byte
	switch strings.ToLower(*format) {
	case "md", "markdown":
		data = []byte(renderDocsMarkdown())
	case "html":
		data = []byte(renderDocsHTML())
	case "pdf":
		b, err := RenderDocsPDF()
		if err != nil {
			fmt.Fprintln(stderr, err)
			return 1
		}
		data = b
	default:
		fmt.Fprintf(stderr, "unknown format %q (want md, html, or pdf)\n", *format)
		return 2
	}

	if *out != "" {
		if err := os.WriteFile(*out, data, 0o644); err != nil {
			fmt.Fprintln(stderr, err)
			return 1
		}
		fmt.Fprintf(stderr, "wrote %s (%d bytes)\n", *out, len(data))
		return 0
	}
	if _, err := stdout.Write(data); err != nil {
		fmt.Fprintln(stderr, err)
		return 1
	}
	return 0
}

// docsMeta returns the title, tool count and generation line shared by every
// format, from an already-built catalog (so renderers don't rebuild it).
func docsMeta(groups []CommandGroup) (title string, tools int, generated string) {
	for _, g := range groups {
		tools += len(g.Commands)
	}
	gen := "generated by Meridian"
	if v := strings.TrimSpace(version.Version); v != "" {
		gen += " " + v
	}
	gen += " · " + time.Now().Format("2006-01-02")
	return "Meridian — Tool Reference", tools, gen
}

func renderDocsMarkdown() string {
	groups := Catalog()
	title, tools, generated := docsMeta(groups)
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", title)
	fmt.Fprintf(&b, "_%d tools across %d groups · %s_\n\n", tools, len(groups), generated)
	b.WriteString("Every tool is in the desktop app and as `meridian-cli <command>`. Most commands accept `--json` for machine-readable output.\n")

	for _, g := range groups {
		fmt.Fprintf(&b, "\n## %s\n", g.Name)
		if g.Note != "" {
			fmt.Fprintf(&b, "_%s_\n", g.Note)
		}
		b.WriteString("\n| Command | Usage | What it does |\n| --- | --- | --- |\n")
		for _, c := range g.Commands {
			fmt.Fprintf(&b, "| `%s` | %s | %s |\n", mdCell(c.Name), mdCell(c.Args), mdCell(c.Desc))
		}
	}

	b.WriteString("\n## Runbook recipes\n")
	b.WriteString("`meridian-cli runbook <id> <target>` composes several tools into one report (also in the app's Runbook tool).\n\n")
	b.WriteString("| Recipe | Steps | What it does |\n| --- | --- | --- |\n")
	for _, p := range rbProfiles {
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", mdCell(p.id), mdCell(recipeSteps(p)), mdCell(p.desc))
	}
	return b.String()
}

func renderDocsHTML() string {
	groups := Catalog()
	title, tools, generated := docsMeta(groups)
	var b strings.Builder
	b.WriteString("<!doctype html>\n<html lang=\"en\"><head><meta charset=\"utf-8\">\n")
	b.WriteString("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n")
	fmt.Fprintf(&b, "<title>%s</title>\n", html.EscapeString(title))
	b.WriteString(`<style>
:root{--ink:#1a1d21;--dim:#6b7076;--line:#e6e8eb;--accent:#0f2a2e;--brand:#2f8a78;}
*{box-sizing:border-box}
body{font:14px/1.5 -apple-system,Segoe UI,Roboto,Helvetica,Arial,sans-serif;color:var(--ink);max-width:960px;margin:0 auto;padding:28px 20px 60px}
h1{font-size:1.9rem;margin:0 0 4px}
.meta{color:var(--dim);font-size:.85rem;margin:0 0 18px}
.lede{color:var(--dim);margin:0 0 22px}
h2{font-size:1.15rem;margin:30px 0 4px;padding-bottom:5px;border-bottom:2px solid var(--brand);color:var(--accent)}
.note{color:var(--dim);font-size:.82rem;margin:2px 0 8px}
table{width:100%;border-collapse:collapse;margin:8px 0 6px}
td,th{text-align:left;vertical-align:top;padding:7px 10px;border-bottom:1px solid var(--line);font-size:.86rem}
th{font-size:.7rem;text-transform:uppercase;letter-spacing:.04em;color:var(--dim)}
code,.cmd{font-family:ui-monospace,SFMono-Regular,Menlo,monospace}
.cmd{font-weight:600;white-space:nowrap}
.usage{font-family:ui-monospace,monospace;color:var(--dim);font-size:.8rem}
@media print{body{max-width:none}h2{break-after:avoid}tr{break-inside:avoid}}
</style>
</head><body>
`)
	fmt.Fprintf(&b, "<h1>%s</h1>\n", html.EscapeString(title))
	fmt.Fprintf(&b, "<p class=\"meta\">%d tools across %d groups · %s</p>\n", tools, len(groups), html.EscapeString(generated))
	b.WriteString("<p class=\"lede\">Every tool is in the desktop app and as <code>meridian-cli &lt;command&gt;</code>. Most commands accept <code>--json</code>.</p>\n")

	for _, g := range groups {
		fmt.Fprintf(&b, "<h2>%s</h2>\n", html.EscapeString(g.Name))
		if g.Note != "" {
			fmt.Fprintf(&b, "<p class=\"note\">%s</p>\n", html.EscapeString(g.Note))
		}
		b.WriteString("<table><tr><th>Command</th><th>Usage</th><th>What it does</th></tr>\n")
		for _, c := range g.Commands {
			fmt.Fprintf(&b, "<tr><td class=\"cmd\">%s</td><td class=\"usage\">%s</td><td>%s</td></tr>\n",
				html.EscapeString(c.Name), html.EscapeString(c.Args), html.EscapeString(c.Desc))
		}
		b.WriteString("</table>\n")
	}

	b.WriteString("<h2>Runbook recipes</h2>\n<p class=\"note\">meridian-cli runbook &lt;id&gt; &lt;target&gt; composes several tools into one report.</p>\n")
	b.WriteString("<table><tr><th>Recipe</th><th>Steps</th><th>What it does</th></tr>\n")
	for _, p := range rbProfiles {
		fmt.Fprintf(&b, "<tr><td class=\"cmd\">%s</td><td class=\"usage\">%s</td><td>%s</td></tr>\n",
			html.EscapeString(p.id), html.EscapeString(recipeSteps(p)), html.EscapeString(p.desc))
	}
	b.WriteString("</table>\n</body></html>\n")
	return b.String()
}

// recipeSteps lists a recipe's step commands, e.g. "linkpath → lldp → arpscan".
func recipeSteps(p rbProfile) string {
	names := make([]string, 0, len(p.steps))
	for _, s := range p.steps {
		names = append(names, s.cmd)
	}
	return strings.Join(names, " → ")
}

// mdCell makes a string safe inside a Markdown table cell: pipes escaped, code
// ticks neutralized, newlines flattened.
func mdCell(s string) string {
	return strings.NewReplacer("|", "\\|", "\n", " ", "`", "'").Replace(s)
}
