package ipspace

import (
	"bufio"
	"fmt"
	"io"
	"regexp"
	"strings"
)

// Terraform import/export. Import scans HCL (.tf) text for the CIDR attributes
// Terraform resources use — cidr_block, ipv6_cidr_block, cidr_blocks — and adds
// each as a record named after the enclosing `resource "<type>" "<name>"` block,
// so existing infrastructure-as-code becomes an inventory without hand-carving.
// Export writes a Terraform `locals` block, the natural way to feed the
// inventory back into IaC.

var (
	reResource = regexp.MustCompile(`^\s*resource\s+"([^"]+)"\s+"([^"]+)"`)
	reCIDR     = regexp.MustCompile(`(?:ipv6_)?cidr_blocks?\s*=\s*(.+)$`)
	reQuoted   = regexp.MustCompile(`"([^"]+/\d+)"`)
)

// ImportTerraform adds records from Terraform HCL. A bad CIDR or an overlap
// conflict skips that entry and is recorded, never aborting the batch.
func (s *Store) ImportTerraform(r io.Reader) (ImportReport, error) {
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 0, 64*1024), 1024*1024)
	var rep ImportReport
	label := ""
	for sc.Scan() {
		line := sc.Text()
		if m := reResource.FindStringSubmatch(line); m != nil {
			label = m[1] + "." + m[2] // e.g. aws_subnet.public
			continue
		}
		if strings.TrimSpace(line) == "}" {
			label = ""
		}
		m := reCIDR.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		for _, q := range reQuoted.FindAllStringSubmatch(m[1], -1) {
			cidr := q[1]
			if _, err := s.Add(cidr, label, Active, nil, "from Terraform"); err != nil {
				rep.Skipped++
				rep.Errors = append(rep.Errors, fmt.Sprintf("%s: %v", cidr, err))
				continue
			}
			rep.Added++
		}
	}
	if err := sc.Err(); err != nil {
		return rep, err
	}
	return rep, nil
}

// ExportTerraform writes the inventory as a Terraform `locals` block.
func (s *Store) ExportTerraform(w io.Writer) error {
	b := bufio.NewWriter(w)
	fmt.Fprintln(b, "# Generated by Meridian — IP-space inventory as Terraform locals")
	fmt.Fprintln(b, "locals {")
	fmt.Fprintln(b, "  meridian_prefixes = [")
	for _, r := range s.Records() {
		fmt.Fprintf(b, "    { prefix = %q, name = %q, status = %q },\n", r.Prefix, r.Name, string(r.Status))
	}
	fmt.Fprintln(b, "  ]")
	fmt.Fprintln(b, "}")
	return b.Flush()
}
